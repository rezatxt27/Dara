export const TERMS = RAW.map(([id, term, aliases, short, long, example]) => ({ id, term, aliases, short, long, example }));
export const TERM = Object.fromEntries(TERMS.map((t) => [t.id, t]));

/** Matching words, longest first (so «NAV ابطال» wins over «NAV»); Latin ones as whole words. */
const MATCH = TERMS.flatMap((t) => t.aliases.map((a) => ({ a, id: t.id }))).sort((x, y) => y.a.length - x.a.length);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
const RE = new RegExp(`(${MATCH.map((m) => esc(m.a)).join('|')})`, 'g');
const LETTER = /[A-Za-zء-يپچژکگی]/;

/**
 * Text → pieces: strings, and {id, text} for a glossary word (whole words only; each term once per text, so a line
 * isn't a sea of underlines).
 */
export function split(text, seen = new Set()) {
  const s = String(text ?? '');
  const out = []; let last = 0; let m;
  RE.lastIndex = 0;
  while ((m = RE.exec(s))) {
    const word = m[0]; const before = s[m.index - 1] || ''; const after = s[m.index + word.length] || '';
    const id = MATCH.find((x) => x.a === word)?.id;
    // inside a longer word («حبابِ» is fine — the joiner isn't a letter; «حبابی» is not)
    if (!id || LETTER.test(before) || LETTER.test(after) || seen.has(id)) continue;
    seen.add(id);
    if (m.index > last) out.push(s.slice(last, m.index));
    out.push({ id, text: word });
    last = m.index + word.length;
  }
  if (last < s.length) out.push(s.slice(last));
  return out;
}

/** Search the glossary: by term, alias or words in the explanation. */
export function search(q) {
  const t = String(q || '').trim().toLowerCase();
  if (!t) return TERMS;
  const hit = (x) => [x.term, ...x.aliases].some((w) => w.toLowerCase().includes(t));
  return [...TERMS.filter(hit), ...TERMS.filter((x) => !hit(x) && (x.short + x.long).toLowerCase().includes(t))];
}
